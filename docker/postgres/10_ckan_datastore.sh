#!/bin/bash
# Crea las bases de datos y usuarios de CKAN y DataStore.
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<-SQL
    CREATE ROLE ${CKAN_DB_USER} LOGIN PASSWORD '${CKAN_DB_PASSWORD}';
    CREATE DATABASE ${CKAN_DB} OWNER ${CKAN_DB_USER} ENCODING 'utf-8';
    CREATE ROLE ${DATASTORE_READONLY_USER} LOGIN PASSWORD '${DATASTORE_READONLY_PASSWORD}';
    CREATE DATABASE ${DATASTORE_DB} OWNER ${CKAN_DB_USER} ENCODING 'utf-8';
SQL
